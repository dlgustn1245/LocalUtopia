namespace Qix
{
    // 게임판의 각 칸이 가질 수 있는 상태.
    public enum CellState
    {
        // 미확보 영역. 플레이어가 이 칸에 들어서면 궤적이 시작된다.
        // flood fill 로 영역을 나눌 때 탐색 대상이 되는 유일한 상태다.
        Empty,

        // 확보한 영역. 테두리는 생성 시점부터 이 상태이며, 플레이어의 안전 지대이자 궤적의 시작/종료 지점이다.
        // 한 번 확보되면 다시 Empty 로 돌아가지 않으므로 flood fill 의 벽 역할을 한다.
        Claimed,

        // 그리는 중인 궤적. 미확보 영역을 가로지르는 동안의 임시 상태다.
        // 궤적을 완성하면 Claimed 로, 사망하면 Empty 로 되돌아간다.
        // 이 상태로 남겨두면 영원히 미확보로 취급되어 이후 영역 분할을 막으므로 반드시 정리해야 한다.
        Trail
    }
}
