namespace Qix
{
    // 꼭짓점 격자의 변(선) 상태. 플레이어가 다닐 수 있는 경로를 이 값으로 판단한다.
    //
    // 이동 가능 여부를 칸 상태에서 유도하지 않는 이유가 여기에 있다.
    // 바깥 테두리를 따라 영역을 확보하면 그 테두리 칸은 사방이 확보 칸이 되어 이동 불가로 잘못 판정된다.
    // 원작 Qix 에서 바깥 테두리는 안쪽이 채워져도 계속 다닐 수 있으므로, 선은 칸과 별개로 기억해야 한다.
    public enum EdgeState
    {
        // 아무것도 없는 변. 미확보 영역을 가로지르므로 그리기로만 지날 수 있다.
        None,

        // 이동 가능한 선. 아레나 바깥 테두리와, 완성된 궤적이 여기에 속한다.
        // 영역 확보 시 flood fill 의 벽 역할을 한다. 양옆 칸이 모두 확보되면 None 으로 정리된다.
        Boundary,

        // 그리는 중인 궤적. 완성하면 Boundary 로, 사망하면 None 으로 되돌아간다.
        // 아직 벽이 아니므로 확보 판정에 참여하지 않는다.
        Trail
    }
}
